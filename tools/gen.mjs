// Boot to ICITY68, dump its in-memory image, analyze and translate it.
// Usage: node tools/gen.mjs   -> writes src/recomp/gen/icity68.js and ../work/icity68.rt.lst
//        node tools/gen.mjs --image-only   -> only ../work/icity68.image.bin / .json (what the
//        exporters need; tools/openic/import.mjs)
import fs from 'node:fs';
import { X68k } from '../src/x68k.js';
import { Disk } from '../src/fs.js';
import { Font } from '../src/font.js';
import { Image, analyze } from '../src/recomp/analyze.js';
import { Translator } from '../src/recomp/translate.js';
import { fmt } from '../src/recomp/decode.js';
import crypto from 'node:crypto';

import { root } from './root.mjs';
const disks = [];
for (let i = 1; i <= 7; i++) disks.push(new Disk(new Uint8Array(fs.readFileSync(`${root}/Genei Toshi (1991)(Microcabin)(Disk ${i} of 7).dim`)), `disk${i}`));
const sys = new X68k({ epoch: Date.UTC(1993, 4, 24, 12, 0, 0), disks, font: new Font(), log: () => {} });
sys.boot([['A:\\ZMUSIC.X', '-U -BICITY.ZPD'], ['A:\\LOAD.X', '']]);
const script = JSON.parse(fs.readFileSync(new URL('./scripts/to-icity68.json', import.meta.url), 'utf8'));
for (let f = 0; f < 3200; f++) {
  for (const ev of script) if (ev.frame === f) { if (ev.key !== undefined) sys.keyEvent(ev.key, true); if (ev.keyup !== undefined) sys.keyEvent(ev.keyup, false); }
  sys.runFrame();
}
const base = sys.human.curPSP + 0x100;
const UNPACK_BASE = 0x8620, CODE_END = 0x2f414; // last code byte is the rts at $2f412
const codeEnd = base + (CODE_END - UNPACK_BASE);
const dataEnd = sys.m.r32(sys.human.curPSP + 0x34);
console.log(`ICITY68 base ${base.toString(16)} code end ${codeEnd.toString(16)} image end ${dataEnd.toString(16)}`);
const img = new Image(sys.m.ram.slice(base, dataEnd), base);
// Keep the analyzed image for tools that do not boot the game (tools/blocktest.mjs).
fs.mkdirSync(`${root}/work`, { recursive: true });
fs.writeFileSync(`${root}/work/icity68.image.bin`, img.bytes);
fs.writeFileSync(`${root}/work/icity68.image.json`, JSON.stringify({ base, codeEnd }));
if (process.argv.includes('--image-only')) process.exit(0);
const an = analyze(img, { codeEnd, entries: [base] });
// Runtime hook points (see src/text/patcher.js): message engine text pointer.
const HOOKS = [0x723b0, 0x72694];
const tr = new Translator(an, { hooks: HOOKS });
const funcs = [...an.funcs.values()].sort((a, b) => a.entry - b.entry);
const parts = [
  '// Generated by tools/gen.mjs from ICITY68.X — do not edit by hand.',
  `export const BASE = 0x${base.toString(16)};`,
  `export const CODE_END = 0x${codeEnd.toString(16)};`,
  'export const functions = new Map();',
  'const def = (a, f) => functions.set(a, f);',
];
// Signature: code bytes at a sample of function entries, checked at runtime so the
// translation is only used once the (self-unpacking) program is really in memory.
const sigFuncs = funcs.filter((_, k) => k % 25 === 0);
parts.push(`export const HOOKS = ${JSON.stringify(HOOKS)};`);
parts.push(`export const SIGNATURE = ${JSON.stringify(sigFuncs.map((f) => [f.entry, [...img.bytes.subarray(f.entry - base, f.entry - base + 8)]]))};`);
let failed = 0;
const hashes = {};
for (const f of funcs) {
  try {
    const code = tr.translate(f);
    hashes[f.entry.toString(16)] = crypto.createHash('sha1').update(code).digest('hex').slice(0, 16);
    parts.push(`def(0x${f.entry.toString(16)}, ${code});`);
  } catch (e) { failed++; parts.push(`// f_${f.entry.toString(16)}: translation failed: ${e.message}`); }
}
// A function whose generated code changed must be verified again.
const verFile = 'src/recomp/gen/icity68.verified.json';
if (fs.existsSync(verFile)) {
  const ver = JSON.parse(fs.readFileSync(verFile, 'utf8'));
  const old = ver.hashes ?? {};
  let reset = 0;
  for (const k of Object.keys(hashes)) {
    if (old[k] !== undefined && old[k] === hashes[k]) continue;
    if (old[k] === undefined && !ver.hashes) continue; // first run with hashes: keep results
    if (ver.pass[k] || ver.fail.includes(k)) { delete ver.pass[k]; ver.fail = ver.fail.filter((x) => x !== k); reset++; }
  }
  ver.hashes = hashes;
  fs.writeFileSync(verFile, JSON.stringify(ver, null, 1));
  console.log(`verification reset for ${reset} changed functions`);
}
fs.mkdirSync('src/recomp/gen', { recursive: true });
fs.writeFileSync('src/recomp/gen/icity68.js', parts.join('\n\n') + '\n');
const lst = [];
for (const f of funcs) {
  lst.push('', `; ==== f_${f.entry.toString(16)} (${f.why})`);
  for (const a of [...f.insnAddrs].sort((x, y) => x - y)) lst.push(`${a.toString(16).padStart(6, '0')}  ${fmt(an.insns.get(a))}`);
}
fs.writeFileSync(`${root}/work/icity68.rt.lst`, lst.join('\n'));
console.log(`functions ${funcs.length}, translation failures ${failed}, output ${(fs.statSync('src/recomp/gen/icity68.js').size / 1024).toFixed(0)} KB`);
